import { createHash } from "node:crypto";
import { describe, expect, it } from "vitest";

import { AssetContentVerificationError, createAssetContentVerifier } from "./asset-content-verifier.js";

function checksum(bytes: Uint8Array): string {
  return createHash("sha256").update(bytes).digest("hex");
}

const PNG_SIGNATURE_AND_IHDR_ONLY = new Uint8Array([
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
  0x00, 0x00, 0x00, 0x0d,
  0x49, 0x48, 0x44, 0x52,
  0x00, 0x00, 0x00, 0x01,
  0x00, 0x00, 0x00, 0x01,
  0x08, 0x06, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00,
]);

const JPEG_SOF_ONLY = new Uint8Array([
  0xff, 0xd8,
  0xff, 0xc0, 0x00, 0x11,
  0x08, 0x00, 0x01, 0x00, 0x01,
  0x03,
  0x01, 0x11, 0x00,
  0x02, 0x11, 0x00,
  0x03, 0x11, 0x00,
]);

const WEBP_VP8X_ONLY = new Uint8Array([
  0x52, 0x49, 0x46, 0x46,
  0x16, 0x00, 0x00, 0x00,
  0x57, 0x45, 0x42, 0x50,
  0x56, 0x50, 0x38, 0x58,
  0x0a, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00,
  0x00, 0x00,
]);

describe("asset content verifier", () => {
  it.each([
    ["image/png", PNG_SIGNATURE_AND_IHDR_ONLY],
    ["image/jpeg", JPEG_SOF_ONLY],
    ["image/webp", WEBP_VP8X_ONLY],
  ] as const)("rejects a structurally incomplete %s image after bounded full decoding", async (mimeType, bytes) => {
    const verifier = createAssetContentVerifier();

    await expect(verifier.verify({
      kind: "product",
      mimeType,
      bytes,
      checksumSha256: checksum(bytes),
    })).rejects.toMatchObject<Partial<AssetContentVerificationError>>({ code: "invalid" });
  });
});
